import { MEANINGFUL_FORM_GAP, MIN_MATCHES_FOR_RATES, possessive, readPick, type DescribedPick } from "./marketReads.ts";
import type { TeamDiscipline } from "./discipline.ts";
import type { TeamForm } from "./teamDepth.ts";

/**
 * A written preview for one fixture, built only from that fixture's numbers.
 *
 * Fixture pages were a pick, two form strings and a row of links -- the same
 * page 7,869 times with the nouns swapped, which is the shape Google declines
 * to crawl ("Discovered, currently not indexed", never fetched). Writing copy
 * per match by hand does not scale, and filling the page with generic prose
 * is the scaled-content pattern Google demotes outright.
 *
 * So this is a sentence bank, not a template. Every sentence has a condition
 * over the data and appears only when that condition holds, and every sentence
 * states a figure that belongs to this fixture. Each has several phrasings,
 * chosen from the fixture id, so one page reads identically on every render --
 * no churn for a crawler comparing fetches -- while neighbouring fixtures read
 * differently.
 *
 * When the data is too thin to say two real things, the preview is omitted
 * rather than padded. That is the same rule that makes a team page earn its
 * indexation in `teamDepth.ts`.
 *
 * Nothing here is generated by a language model: the text must be checkable
 * against the published prediction and must never state a fact the database
 * does not hold.
 */

export type PreviewPrediction = {
  marketKey: string;
  selection: string;
  /** 0-100, as the API serves it. */
  confidence: number;
  /** ISO publication time; card lines are described only after CARD_UNIT_FIXED_AT. */
  publishedAt?: string;
};

export type PreviewOdds = { label: string; value: string };

export type PreviewInput = {
  id: number;
  homeTeam: string;
  awayTeam: string;
  /** Space-separated W/D/L, most recent first, as the API serves it. */
  homeForm: string;
  awayForm: string;
  /** Figures from `teamForm`, excluding this fixture. Null when unavailable. */
  homeStats: TeamForm | null;
  awayStats: TeamForm | null;
  /** The headline prediction, or null when none is published. */
  prediction: PreviewPrediction | null;
  predictions: PreviewPrediction[];
  odds: PreviewOdds[];
  /** Card records from before kickoff, when the API has them. */
  homeDiscipline?: TeamDiscipline | null;
  awayDiscipline?: TeamDiscipline | null;
};

export type PreviewSection = {
  heading: string;
  sentences: string[];
  /** "list" when each sentence stands alone, as in the market-by-market read. */
  style?: "prose" | "list";
};

export { MIN_MATCHES_FOR_RATES };

/** A preview must say at least this many things to be worth a section. */
export const MIN_SENTENCES = 3;

// FNV-1a. Stable across runtimes, which Math.random and object key order are
// not, so the same fixture always gets the same phrasing.
function hash(text: string) {
  let value = 0x811c9dc5;
  for (let index = 0; index < text.length; index += 1) {
    value ^= text.charCodeAt(index);
    value = Math.imul(value, 0x01000193);
  }
  return value >>> 0;
}

function pick<T>(id: number, key: string, options: readonly T[]): T {
  return options[hash(`${id}:${key}`) % options.length];
}

function pct(part: number, total: number) {
  return Math.round((part / total) * 100);
}

function perMatch(total: number, matches: number) {
  return (total / matches).toFixed(1);
}

type FormSummary = { letters: string[]; won: number; drawn: number; lost: number; points: number };

function readForm(form: string): FormSummary | null {
  const letters = String(form ?? "").trim().toUpperCase().split(/\s+/).filter((letter) => ["W", "D", "L"].includes(letter)).slice(0, 5);
  if (letters.length < 3) return null;
  const won = letters.filter((letter) => letter === "W").length;
  const drawn = letters.filter((letter) => letter === "D").length;
  const lost = letters.length - won - drawn;
  return { letters, won, drawn, lost, points: won * 3 + drawn };
}

function record(form: FormSummary) {
  return `${form.won}W ${form.drawn}D ${form.lost}L`;
}

function formSentences(input: PreviewInput): string[] {
  const home = readForm(input.homeForm);
  const away = readForm(input.awayForm);
  const out: string[] = [];

  for (const [team, form, side] of [[input.homeTeam, home, "home"], [input.awayTeam, away, "away"]] as const) {
    if (!form) continue;
    const n = form.letters.length;
    if (form.lost === 0) {
      out.push(pick(input.id, `unbeaten-${side}`, [
        `${team} are unbeaten in their last ${n} (${record(form)}).`,
        `${team} have not lost in ${n} matches: ${form.won} wins and ${form.drawn} draws.`,
        `Nobody has beaten ${team} in their last ${n} outings (${record(form)}).`,
      ]));
    } else if (form.won === 0) {
      out.push(pick(input.id, `winless-${side}`, [
        `${team} are without a win in their last ${n} (${record(form)}).`,
        `${team} have gone ${n} matches without winning: ${form.drawn} draws and ${form.lost} defeats.`,
      ]));
    } else if (form.letters[0] === "W" && form.letters[1] === "W") {
      const streak = form.letters.findIndex((letter) => letter !== "W");
      const run = streak === -1 ? n : streak;
      out.push(pick(input.id, `streak-${side}`, [
        `${team} have won their last ${run} and ${form.won} of their last ${n}.`,
        `${team} are on a ${run}-match winning run, with ${form.points} points from their last ${n}.`,
      ]));
    } else {
      out.push(pick(input.id, `record-${side}`, [
        `${team} have taken ${form.points} points from their last ${n} (${form.letters.join(" ")}).`,
        `${possessive(team)} last ${n}: ${record(form)}, ${form.points} points.`,
      ]));
    }
  }

  if (home && away && home.letters.length === away.letters.length) {
    const gap = home.points - away.points;
    if (Math.abs(gap) >= MEANINGFUL_FORM_GAP) {
      const [better, worse, high, low] = gap > 0
        ? [input.homeTeam, input.awayTeam, home.points, away.points]
        : [input.awayTeam, input.homeTeam, away.points, home.points];
      out.push(pick(input.id, "form-gap", [
        `On form, ${better} hold a clear edge: ${high} points to ${possessive(worse)} ${low} over the same number of games.`,
        `${better} have collected ${high - low} more points than ${worse} across their recent matches.`,
      ]));
    } else {
      out.push(pick(input.id, "form-level", [
        `There is little between the sides on recent form: ${home.points} points to ${away.points}.`,
        `Recent form is close, ${home.points} points for ${input.homeTeam} against ${away.points} for ${input.awayTeam}.`,
      ]));
    }
  }
  return out;
}

function usable(stats: TeamForm | null): stats is TeamForm {
  return Boolean(stats && stats.matches >= MIN_MATCHES_FOR_RATES);
}

function goalSentences(input: PreviewInput): string[] {
  const out: string[] = [];
  const home = usable(input.homeStats) ? input.homeStats : null;
  const away = usable(input.awayStats) ? input.awayStats : null;

  for (const [team, stats, side] of [[input.homeTeam, home, "home"], [input.awayTeam, away, "away"]] as const) {
    if (!stats) continue;
    out.push(pick(input.id, `goals-${side}`, [
      `${team} average ${perMatch(stats.goalsFor, stats.matches)} goals scored and ${perMatch(stats.goalsAgainst, stats.matches)} conceded per match (${stats.matches} recorded).`,
      `Across ${stats.matches} recorded matches, ${team} score ${perMatch(stats.goalsFor, stats.matches)} and concede ${perMatch(stats.goalsAgainst, stats.matches)} per game.`,
    ]));
    const cleanRate = pct(stats.cleanSheets, stats.matches);
    if (cleanRate >= 40) {
      out.push(pick(input.id, `clean-${side}`, [
        `${team} have kept ${stats.cleanSheets} clean sheets in ${stats.matches} (${cleanRate}%).`,
        `${team} keep a clean sheet in ${cleanRate}% of their matches.`,
      ]));
    }
  }

  if (home && away) {
    const homeBtts = pct(home.bothTeamsScored, home.matches);
    const awayBtts = pct(away.bothTeamsScored, away.matches);
    if (homeBtts >= 60 && awayBtts >= 60) {
      out.push(pick(input.id, "btts-high", [
        `Both teams have scored in ${homeBtts}% of ${possessive(input.homeTeam)} matches and ${awayBtts}% of ${possessive(input.awayTeam)}.`,
        `Goals at both ends are the norm for these sides: BTTS landed in ${homeBtts}% and ${awayBtts}% of their recorded games.`,
      ]));
    } else if (homeBtts <= 35 && awayBtts <= 35) {
      out.push(pick(input.id, "btts-low", [
        `Both teams scored in only ${homeBtts}% of ${possessive(input.homeTeam)} matches and ${awayBtts}% of ${possessive(input.awayTeam)}.`,
        `One side usually fails to score in these teams' games: BTTS came in just ${homeBtts}% and ${awayBtts}% of the time.`,
      ]));
    }
    const homeOver = pct(home.overTwoFive, home.matches);
    const awayOver = pct(away.overTwoFive, away.matches);
    const averageOver = Math.round((homeOver + awayOver) / 2);
    if (averageOver >= 60) {
      out.push(pick(input.id, "over-high", [
        `Over 2.5 goals came in ${homeOver}% of ${possessive(input.homeTeam)} matches and ${awayOver}% of ${possessive(input.awayTeam)}.`,
        `These are high-scoring sides: an average of ${averageOver}% of their games went over 2.5 goals.`,
      ]));
    } else if (averageOver <= 35) {
      out.push(pick(input.id, "over-low", [
        `Only ${homeOver}% of ${input.homeTeam}'s matches and ${awayOver}% of ${input.awayTeam}'s went over 2.5 goals.`,
        `Low totals are typical here: just ${averageOver}% of these teams' games went over 2.5 goals on average.`,
      ]));
    }
  }
  return out;
}

function cardRecord(stats: TeamDiscipline | null | undefined): stats is TeamDiscipline {
  return Boolean(stats && stats.matches >= MIN_MATCHES_FOR_RATES);
}

/**
 * Card figures from each team's recent matches.
 *
 * Only teams with four or more recorded matches are described, the same bar
 * as every other rate on the page. Red cards are mentioned only when there is
 * more than one: a single dismissal in ten games is ordinary and saying so
 * would read as a pattern.
 */
function disciplineSentences(input: PreviewInput): string[] {
  const out: string[] = [];
  const home = cardRecord(input.homeDiscipline) ? input.homeDiscipline : null;
  const away = cardRecord(input.awayDiscipline) ? input.awayDiscipline : null;

  for (const [team, record, side] of [[input.homeTeam, home, "home"], [input.awayTeam, away, "away"]] as const) {
    if (!record) continue;
    const yellowRate = perMatch(record.yellowCards, record.matches);
    out.push(pick(input.id, `cards-${side}`, [
      `${team} have been shown ${record.yellowCards} yellow ${record.yellowCards === 1 ? "card" : "cards"} in their last ${record.matches} matches, ${yellowRate} a game.`,
      `${team} average ${yellowRate} yellow cards a game over their last ${record.matches}.`,
    ]));
    if (record.redCards >= 2) {
      out.push(`${team} have had ${record.redCards} players sent off in that run.`);
    }
  }

  if (home && away) {
    const homeRate = home.yellowCards / home.matches;
    const awayRate = away.yellowCards / away.matches;
    const [higher, lower, high, low] = homeRate >= awayRate
      ? [input.homeTeam, input.awayTeam, homeRate, awayRate]
      : [input.awayTeam, input.homeTeam, awayRate, homeRate];
    if (high - low >= 0.8) {
      out.push(`${higher} are the more booked side, by ${(high - low).toFixed(1)} yellow cards a game over ${lower}.`);
    }
    const combined = ((home.matchCards / home.matches) + (away.matchCards / away.matches)) / 2;
    out.push(pick(input.id, "match-cards", [
      `Games involving these sides have averaged ${combined.toFixed(1)} cards in total.`,
      `Counting both teams, their recent matches have produced ${combined.toFixed(1)} cards a game.`,
    ]));
  } else {
    const only = home ?? away;
    if (only) {
      out.push(`Those matches averaged ${perMatch(only.matchCards, only.matches)} cards in total, counting both sides.`);
    }
  }
  return out;
}

/** How many other markets the market-by-market list may cover. */
export const MAX_MARKET_READS = 8;

function capitalize(text: string) {
  return text ? text[0].toUpperCase() + text.slice(1) : text;
}

/** The headline outcome, with its market named when the reading is generic. */
function headlinePhrase(read: DescribedPick) {
  return read.generic ? `${read.outcome} (${read.market})` : read.outcome;
}

function modelSentences(input: PreviewInput): string[] {
  const out: string[] = [];
  const read = input.prediction ? readPick(input, input.prediction) : null;
  if (!read) return out;
  const phrase = headlinePhrase(read);
  const confidence = read.confidence;

  if (confidence >= 70) {
    out.push(pick(input.id, "headline-high", [
      `The SokaLens model's strongest call here is ${phrase} at ${confidence}% confidence.`,
      `Our model backs ${phrase} with ${confidence}% confidence, a high reading for this model.`,
    ]));
  } else if (confidence >= 50) {
    out.push(pick(input.id, "headline-mid", [
      `The SokaLens model leans towards ${phrase} at ${confidence}% confidence.`,
      `Our model's pick is ${phrase}, rated at ${confidence}%.`,
    ]));
  } else {
    out.push(pick(input.id, "headline-low", [
      `This is a close call: the model's pick, ${phrase}, carries ${confidence}% confidence.`,
      `The model sees no clear favourite outcome; its pick of ${phrase} rates only ${confidence}%.`,
    ]));
  }
  if (read.evidence) out.push(read.evidence);
  return out;
}

function marketKeyOf(prediction: PreviewPrediction) {
  return String(prediction.marketKey ?? "").trim().toLowerCase();
}

/**
 * One line per other published market, strongest first.
 *
 * One pick per market: the engine publishes a single selection per market, but
 * a re-publication can briefly leave two, and listing "Over 2.5" beside "Under
 * 2.5" would contradict itself. The highest confidence wins, and the headline's
 * market is left to the headline.
 */
function marketSentences(input: PreviewInput): string[] {
  const headline = input.prediction ? readPick(input, input.prediction) : null;
  const headlineKey = headline && input.prediction ? marketKeyOf(input.prediction) : null;
  // Evidence is about the teams, not the market, so several picks can share
  // one sentence ("10 points to 13"). Say it once, where it first applies.
  const cited = new Set<string>(headline?.evidence ? [headline.evidence] : []);
  const best = new Map<string, { read: DescribedPick; order: number }>();
  input.predictions.forEach((prediction, order) => {
    const key = marketKeyOf(prediction);
    if (key === headlineKey) return;
    const read = readPick(input, prediction);
    if (!read) return;
    const current = best.get(key);
    if (!current || read.confidence > current.read.confidence) best.set(key, { read, order });
  });
  return [...best.values()]
    .sort((a, b) => b.read.confidence - a.read.confidence || a.order - b.order)
    .slice(0, MAX_MARKET_READS)
    .map(({ read }) => {
      const line = `${read.market}: ${read.generic ? read.outcome : capitalize(read.outcome)}, ${read.confidence}%.`;
      if (!read.evidence || cited.has(read.evidence)) return line;
      cited.add(read.evidence);
      return `${line} ${read.evidence}`;
    });
}

const RESULT_ALIASES: Record<string, "home" | "draw" | "away"> = {
  home: "home", "1": "home", draw: "draw", x: "draw", away: "away", "2": "away",
};

function price(odds: PreviewOdds[], label: string) {
  const entry = odds.find((item) => String(item?.label ?? "").trim().toLowerCase() === label);
  const raw = String(entry?.value ?? "").trim();
  // Decimal prices only. A price at or below 1.00 pays nothing and implies
  // 100% or more; it is a feed error, not a favourite.
  if (!/^\d+(\.\d+)?$/.test(raw)) return null;
  const value = Number(raw);
  return value > 1 && value < 1000 ? value : null;
}

function oddsSentences(input: PreviewInput): string[] {
  const out: string[] = [];
  const prices = { home: price(input.odds, "home"), draw: price(input.odds, "draw"), away: price(input.odds, "away") };
  if (prices.home === null || prices.away === null) return out;

  if (prices.draw !== null && prices.draw < prices.home && prices.draw < prices.away) {
    out.push(`The market expects a tight game: the draw is the shortest price at ${prices.draw.toFixed(2)}.`);
  } else if (prices.home === prices.away) {
    out.push(`The market cannot separate the sides: both are priced at ${prices.home.toFixed(2)}.`);
  } else {
    const favourite = prices.home < prices.away ? input.homeTeam : input.awayTeam;
    const favouritePrice = Math.min(prices.home, prices.away);
    out.push(pick(input.id, "favourite", [
      `The market makes ${favourite} favourites at ${favouritePrice.toFixed(2)}.`,
      `${favourite} are the bookmakers' favourites, priced at ${favouritePrice.toFixed(2)}.`,
    ]));
  }

  const oneXTwo = input.predictions.find((item) => ["1x2", "match_result"].includes(marketKeyOf(item)) && readPick(input, item) !== null);
  const side = oneXTwo ? RESULT_ALIASES[oneXTwo.selection.trim().toLowerCase()] : undefined;
  const sidePrice = side ? prices[side] : null;
  if (oneXTwo && side && sidePrice !== null) {
    const implied = Math.round(100 / sidePrice);
    const model = Math.round(oneXTwo.confidence);
    const outcome = side === "draw" ? "a draw" : side === "home" ? `a ${input.homeTeam} win` : `a ${input.awayTeam} win`;
    if (Math.abs(model - implied) >= 5) {
      out.push(pick(input.id, "odds-gap", [
        `The model puts ${outcome} at ${model}%, against ${implied}% implied by the ${sidePrice.toFixed(2)} price.`,
        `For ${outcome}, the model's ${model}% differs from the ${implied}% the market implies at ${sidePrice.toFixed(2)}.`,
      ]));
    } else {
      out.push(`The model's ${model}% for ${outcome} is close to the ${implied}% the ${sidePrice.toFixed(2)} price implies.`);
    }
  }
  return out;
}

/**
 * Build the preview, or return null when there is too little to say.
 *
 * Sections with nothing in them are dropped, and the whole preview is dropped
 * below MIN_SENTENCES: a single sentence restating the form strings already on
 * the page is exactly the thin content this exists to replace.
 */
/**
 * The supporting evidence for each published market, keyed by market key.
 *
 * The refreshed match page prints a one-line rationale inside every market
 * card. That line already exists inside `marketSentences`, but only as prose
 * of the shape "Double Chance: Home or draw, 46%. <evidence>", which a card
 * cannot use: it restates the market, selection and percentage the card
 * already shows in three larger typefaces.
 *
 * So this returns the evidence clause alone, from the same `readPick` the
 * written preview uses. Parsing it back out of those sentences would have been
 * the alternative, and it would break the first time the sentence template
 * changed.
 *
 * Differences from `marketSentences`, both deliberate:
 *  - the headline market is included, because the hero prints its own note and
 *    the card for it still needs a line.
 *  - evidence is NOT de-duplicated across markets. In prose a repeated "10
 *    points to 13" reads as padding, which is why the sentences say it once.
 *    Cards are read individually and in any order, so a card left blank
 *    because a sibling card claimed the shared evidence first would look
 *    broken rather than concise.
 *
 * A market with no evidence to offer is absent from the map rather than
 * present and empty: the caller decides how to render a card without a reason,
 * and an empty string would render as a blank line that looks like a fault.
 */
export function marketReasons(input: PreviewInput): Map<string, string> {
  const reasons = new Map<string, string>();
  for (const prediction of input.predictions) {
    const key = marketKeyOf(prediction);
    if (!key || reasons.has(key)) continue;
    const read = readPick(input, prediction);
    if (read?.evidence) reasons.set(key, read.evidence);
  }
  return reasons;
}

export function buildMatchPreview(input: PreviewInput): PreviewSection[] | null {
  const sections: PreviewSection[] = [
    { heading: "Form", sentences: formSentences(input) },
    { heading: "Goals", sentences: goalSentences(input) },
    { heading: "Discipline", sentences: disciplineSentences(input) },
    { heading: "The model's view", sentences: modelSentences(input) },
    { heading: "Market by market", sentences: marketSentences(input), style: "list" as const },
    { heading: "The market", sentences: oddsSentences(input) },
  ].filter((section) => section.sentences.length > 0);
  const total = sections.reduce((sum, section) => sum + section.sentences.length, 0);
  return total >= MIN_SENTENCES ? sections : null;
}
